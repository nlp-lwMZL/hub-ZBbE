def predict(text):
    scores = {}
    for label, words in KEYWORDS.items():
        scores[label] = 0
        for w in words:
            scores[label] += text.count(w)
    best = max(scores, key=scores.get)
    if scores[best] > 0:
        return best
    return "109"


